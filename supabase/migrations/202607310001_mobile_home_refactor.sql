create or replace function private.is_household_member(target_household_id text)
returns boolean language sql stable security definer set search_path = '' as $$
    select exists (
        select 1 from public.household_memberships
        where user_id = (select auth.uid()) and household_id = target_household_id
    );
$$;

create or replace function public.create_household(household_name text, member_name text)
returns text language plpgsql security definer set search_path = '' as $$
declare
    new_household_id text := gen_random_uuid()::text;
    new_invite_code text := upper(substr(encode(extensions.gen_random_bytes(8), 'hex'), 1, 12));
    now_text text := now()::text;
begin
    if auth.uid() is null then raise exception 'Authentication required'; end if;
    household_name := trim(household_name);
    member_name := trim(member_name);
    if length(household_name) not between 1 and 80 or length(member_name) not between 1 and 40 then
        raise exception 'Invalid household or member name';
    end if;
    insert into public.households(id, name, invite_code, created_at)
    values (new_household_id, household_name, new_invite_code, now_text);
    insert into public.household_memberships(user_id, household_id, role, created_at)
    values (auth.uid(), new_household_id, 'owner', now_text);
    insert into public.members(id, household_id, user_id, name, role, created_at)
    values (gen_random_uuid()::text, new_household_id, auth.uid(), member_name, 'Owner', now_text);
    return new_household_id;
end;
$$;

create or replace function public.join_household(household_invite_code text, member_name text)
returns text language plpgsql security definer set search_path = '' as $$
declare
    target_household_id text;
    now_text text := now()::text;
begin
    if auth.uid() is null then raise exception 'Authentication required'; end if;
    member_name := trim(member_name);
    if length(member_name) not between 1 and 40 then raise exception 'Invalid member name'; end if;
    select id into target_household_id from public.households where invite_code = upper(trim(household_invite_code));
    if target_household_id is null then raise exception 'Invalid household invite'; end if;
    if exists (select 1 from public.household_memberships where user_id = auth.uid() and household_id = target_household_id) then
        raise exception 'This account already belongs to this household';
    end if;
    insert into public.household_memberships(user_id, household_id, role, created_at)
    values (auth.uid(), target_household_id, 'member', now_text);
    insert into public.members(id, household_id, user_id, name, role, created_at)
    values (gen_random_uuid()::text, target_household_id, auth.uid(), member_name, '', now_text);
    return target_household_id;
end;
$$;

create or replace function public.create_conversation(session_data jsonb, first_message text)
returns void language plpgsql set search_path = '' as $$
declare session_row public.conversation_sessions;
begin
    session_row := jsonb_populate_record(null::public.conversation_sessions, session_data);
    insert into public.conversation_sessions select (session_row).*;
    insert into public.conversation_messages(session_id, role, content, created_at)
    values (session_row.id, 'user', first_message, session_row.created_at);
end;
$$;

create or replace function public.append_conversation_message(
    target_session_id text, message_role text, message_content text, now_text text
)
returns void language plpgsql set search_path = '' as $$
begin
    insert into public.conversation_messages(session_id, role, content, created_at)
    values (target_session_id, message_role, message_content, now_text);
    update public.conversation_sessions set updated_at = now_text where id = target_session_id;
end;
$$;

create or replace function public.create_board_items(
    target_household_id text, target_timezone text, submission_data jsonb, item_data jsonb
)
returns text[] language plpgsql set search_path = '' as $$
declare
    submission_row public.submissions;
    item_ids text[];
begin
    update public.households set timezone = target_timezone where id = target_household_id;
    submission_row := jsonb_populate_record(null::public.submissions, submission_data);
    insert into public.submissions select (submission_row).* on conflict (id) do nothing;
    insert into public.items select * from jsonb_populate_recordset(null::public.items, item_data)
    on conflict (submission_id, source_index) do nothing;
    select array_agg(id order by source_index) into item_ids from public.items where submission_id = submission_row.id;
    return coalesce(item_ids, array[]::text[]);
end;
$$;


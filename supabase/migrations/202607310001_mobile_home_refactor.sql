create table public.households (
    id text primary key,
    name text not null,
    invite_code text not null unique,
    timezone text not null default 'UTC',
    city text,
    country_code text,
    latitude double precision,
    longitude double precision,
    memory text not null default '',
    created_at text not null
);

create table public.household_memberships (
    user_id uuid not null references auth.users(id) on delete cascade,
    household_id text not null references public.households(id) on delete cascade,
    role text not null check (role in ('owner', 'member')),
    created_at text not null,
    primary key (user_id, household_id)
);

create table public.members (
    id text primary key,
    household_id text not null references public.households(id) on delete cascade,
    user_id uuid references auth.users(id) on delete set null,
    name text not null,
    role text not null default '',
    deleted_at text,
    created_at text not null
);

create unique index members_household_user_unique
    on public.members(household_id, user_id) where user_id is not null;

create table public.submissions (
    id text primary key,
    household_id text not null references public.households(id) on delete cascade,
    created_by text not null references public.members(id),
    source text not null check (source in ('conversation', 'text', 'audio')),
    original_text text not null,
    timezone text not null,
    created_at text not null
);

create table public.items (
    id text primary key,
    household_id text not null references public.households(id) on delete cascade,
    submission_id text references public.submissions(id),
    source_index integer,
    kind text not null check (kind in ('event', 'task', 'note')),
    title text not null,
    details text not null default '',
    preparation text,
    remind_member_id text references public.members(id),
    completed_at text,
    start_at text,
    end_at text,
    start_date text,
    due_at text,
    due_date text,
    reminder_at text,
    all_day integer not null default 0 check (all_day in (0, 1)),
    recurrence text check (recurrence is null or recurrence in ('daily', 'weekly', 'monthly')),
    monthly_on_last_day integer not null default 0 check (monthly_on_last_day in (0, 1)),
    recurrence_until text,
    created_by text not null references public.members(id),
    created_at text not null,
    updated_at text not null,
    unique (submission_id, source_index),
    check (kind = 'task' or completed_at is null),
    check (kind <> 'note' or (remind_member_id is null and reminder_at is null and preparation is null)),
    check (kind = 'event' or recurrence is null)
);

create table public.recurrence_exceptions (
    series_id text not null references public.items(id) on delete cascade,
    occurrence_date text not null,
    cancelled integer not null default 0 check (cancelled in (0, 1)),
    start_at text,
    end_at text,
    start_date text,
    title text,
    details text,
    preparation text,
    updated_at text not null,
    primary key (series_id, occurrence_date)
);

create table public.item_notes (
    id text primary key,
    item_id text not null references public.items(id) on delete cascade,
    member_id text not null references public.members(id),
    content text not null check (length(content) between 1 and 1000),
    created_at text not null

using ((select private.is_household_member(id))) with check ((select private.is_household_member(id)));
create policy memberships_own_read on public.household_memberships for select to authenticated
using (user_id = (select auth.uid()));
create policy members_household_access on public.members for all to authenticated
using ((select private.is_household_member(household_id))) with check ((select private.is_household_member(household_id)));
create policy submissions_household_access on public.submissions for all to authenticated
using ((select private.is_household_member(household_id)))
with check (
    (select private.is_household_member(household_id))
    and exists (select 1 from public.members where id = created_by and members.household_id = submissions.household_id)
);
create policy items_household_access on public.items for all to authenticated
using ((select private.is_household_member(household_id)))
with check (
    (select private.is_household_member(household_id))
    and exists (select 1 from public.members where id = created_by and members.household_id = items.household_id)
    and (
        remind_member_id is null
        or exists (select 1 from public.members where id = remind_member_id and members.household_id = items.household_id)
    )
);
create policy exceptions_household_access on public.recurrence_exceptions for all to authenticated
using (exists (select 1 from public.items where id = series_id and (select private.is_household_member(household_id))))
with check (exists (select 1 from public.items where id = series_id and (select private.is_household_member(household_id))));
create policy item_notes_household_access on public.item_notes for all to authenticated
using (exists (select 1 from public.items where id = item_id and (select private.is_household_member(household_id))))
with check (
    exists (
        select 1 from public.items
        join public.members on members.id = item_notes.member_id and members.household_id = items.household_id
        where items.id = item_notes.item_id and (select private.is_household_member(items.household_id))
    )
);
create policy conversations_household_access on public.conversation_sessions for all to authenticated
using ((select private.is_household_member(household_id)))
with check (
    (select private.is_household_member(household_id))
    and exists (select 1 from public.members where id = actor_id and members.household_id = conversation_sessions.household_id)
);
create policy conversation_messages_household_access on public.conversation_messages for all to authenticated
using (exists (select 1 from public.conversation_sessions where id = session_id and (select private.is_household_member(household_id))))
with check (exists (select 1 from public.conversation_sessions where id = session_id and (select private.is_household_member(household_id))));

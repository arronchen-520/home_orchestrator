create extension if not exists pgcrypto;
create schema if not exists private;

create table if not exists public.households (
    id text primary key,
    name text not null,
    invite_code text not null unique,
    timezone text not null default 'UTC',
    city text,
    country_code text,
    latitude double precision,
    longitude double precision,
    memory text not null default '',
    created_at text not null
);

create table if not exists public.household_memberships (
    user_id uuid primary key references auth.users(id) on delete cascade,
    household_id text not null references public.households(id) on delete cascade,
    role text not null check (role in ('owner', 'member')),
    created_at text not null
);

create table if not exists public.members (
    id text primary key,
    household_id text not null references public.households(id) on delete cascade,
    user_id uuid unique references auth.users(id) on delete set null,
    name text not null,
    role text not null default '',
    deleted_at text,
    created_at text not null
);

create table if not exists public.submissions (
    id text primary key,
    household_id text not null references public.households(id) on delete cascade,
    created_by text not null references public.members(id),
    source text not null check (source in ('text', 'audio')),
    original_text text not null,
    timezone text not null,
    created_at text not null
);

create table if not exists public.items (
    id text primary key,
    household_id text not null references public.households(id) on delete cascade,
    submission_id text references public.submissions(id),
    source_index integer,
    kind text not null check (kind in ('event', 'task', 'note')),
    title text not null,
    details text not null default '',
    preparation text,
    owner_id text references public.members(id),
    assignment_state text check (
        assignment_state is null or assignment_state in ('pending', 'accepted')
    ),
    status text check (
        status is null or status in ('unclaimed', 'claimed', 'done')
    ),
    start_at text,
    end_at text,
    start_date text,
    due_at text,
    due_date text,
    reminder_at text,
    all_day integer not null default 0 check (all_day in (0, 1)),
    recurrence text check (
        recurrence is null or recurrence in ('daily', 'weekly', 'monthly')
    ),
    monthly_on_last_day integer not null default 0 check (
        monthly_on_last_day in (0, 1)
    ),
    recurrence_until text,
    created_by text not null references public.members(id),
    created_at text not null,
    updated_at text not null,
    unique (submission_id, source_index)
);

create table if not exists public.recurrence_exceptions (
    series_id text not null references public.items(id) on delete cascade,
    occurrence_date text not null,
    cancelled integer not null default 0 check (cancelled in (0, 1)),
    start_at text,
    end_at text,
    start_date text,
    title text,
    details text,
    preparation text,
    updated_at text not null,
    primary key (series_id, occurrence_date)
);

create table if not exists public.chat_sessions (
    id text primary key,
    household_id text not null references public.households(id) on delete cascade,
    actor_id text not null references public.members(id),
    kind text not null check (kind in ('intake', 'assistant')),
    status text not null check (
        status in ('active', 'clarifying', 'review', 'confirmed')
    ),
    owner_id text references public.members(id),
    source text not null check (source in ('text', 'audio')),
    timezone text not null,
    clarification_count integer not null default 0,
    payload_json text not null default '{}',
    created_at text not null,
    updated_at text not null
);

create table if not exists public.chat_messages (
    id bigint generated by default as identity primary key,
    session_id text not null references public.chat_sessions(id) on delete cascade,
    role text not null check (role in ('user', 'assistant')),
    content text not null,
    created_at text not null
);

create index if not exists memberships_household
    on public.household_memberships(household_id);
create index if not exists members_household
    on public.members(household_id);
create index if not exists items_household_status
    on public.items(household_id, status);
create index if not exists items_household_start
    on public.items(household_id, start_at, start_date);
create index if not exists items_household_due
    on public.items(household_id, due_at, due_date);
create index if not exists chat_messages_session
    on public.chat_messages(session_id, id);

create or replace function private.is_household_member(target_household_id text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.household_memberships
        where user_id = (select auth.uid())
          and household_id = target_household_id
    );
$$;

revoke all on function private.is_household_member(text) from public;
grant execute on function private.is_household_member(text) to authenticated;

create or replace function public.create_household(
    household_name text,
    member_name text
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
    new_household_id text := gen_random_uuid()::text;
    new_invite_code text := upper(
        substr(encode(extensions.gen_random_bytes(8), 'hex'), 1, 12)
    );
    now_text text := now()::text;
begin
    if auth.uid() is null then
        raise exception 'Authentication required';
    end if;
    if exists (
        select 1 from public.household_memberships where user_id = auth.uid()
    ) then
        raise exception 'This account already belongs to a household';
    end if;
    household_name := trim(household_name);
    member_name := trim(member_name);
    if length(household_name) not between 1 and 80
       or length(member_name) not between 1 and 40 then
        raise exception 'Invalid household or member name';
    end if;

    insert into public.households (
        id, name, invite_code, created_at
    ) values (
        new_household_id, household_name, new_invite_code, now_text
    );
    insert into public.household_memberships (
        user_id, household_id, role, created_at
    ) values (
        auth.uid(), new_household_id, 'owner', now_text
    );
    insert into public.members (
        id, household_id, user_id, name, role, created_at
    ) values (
        gen_random_uuid()::text, new_household_id, auth.uid(),
        member_name, 'Owner', now_text
    );
    return new_household_id;
end;
$$;

create or replace function public.join_household(
    household_invite_code text,
    member_name text
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
    target_household_id text;
    now_text text := now()::text;
begin
    if auth.uid() is null then
        raise exception 'Authentication required';
    end if;
    if exists (
        select 1 from public.household_memberships where user_id = auth.uid()
    ) then
        raise exception 'This account already belongs to a household';
    end if;
    member_name := trim(member_name);
    if length(member_name) not between 1 and 40 then
        raise exception 'Invalid member name';
    end if;

    select id into target_household_id
    from public.households
    where invite_code = upper(trim(household_invite_code));
    if target_household_id is null then
        raise exception 'Invalid household invite';
    end if;

    insert into public.household_memberships (
        user_id, household_id, role, created_at
    ) values (
        auth.uid(), target_household_id, 'member', now_text
    );
    insert into public.members (
        id, household_id, user_id, name, role, created_at
    ) values (
        gen_random_uuid()::text, target_household_id, auth.uid(),
        member_name, '', now_text
    );
    return target_household_id;
end;
$$;

